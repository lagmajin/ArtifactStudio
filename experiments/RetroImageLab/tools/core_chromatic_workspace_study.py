"""Differentially compare dual-buffer and reused-buffer Core chromatic models."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
CASES = ((1, 1), (1, 13), (17, 1), (17, 13), (256, 192), (640, 360), (1920, 1080))
SHIFTS = ((1, 0), (-1, 0), (0, 1), (0, -1), (1, 1), (-7, 4), (48, -31))


def shift_into(dst: np.ndarray, src: np.ndarray, sx: int, sy: int) -> None:
    h, w = src.shape
    ys = np.clip(np.arange(h) + sy, 0, h - 1)
    xs = np.clip(np.arange(w) + sx, 0, w - 1)
    dst[:] = src[ys[:, None], xs[None, :]]


def dual_workspace(rgb: np.ndarray, sx: int, sy: int) -> np.ndarray:
    result = rgb.copy()
    r_tmp = np.empty(rgb.shape[:2], dtype=np.float32)
    b_tmp = np.empty(rgb.shape[:2], dtype=np.float32)
    shift_into(r_tmp, rgb[:, :, 0], sx, sy)
    shift_into(b_tmp, rgb[:, :, 2], -sx, -sy)
    result[:, :, 0] = r_tmp
    result[:, :, 2] = b_tmp
    return result


def reused_workspace(rgb: np.ndarray, sx: int, sy: int) -> np.ndarray:
    result = rgb.copy()
    scratch = np.empty(rgb.shape[:2], dtype=np.float32)
    shift_into(scratch, rgb[:, :, 0], sx, sy)
    result[:, :, 0] = scratch
    shift_into(scratch, rgb[:, :, 2], -sx, -sy)
    result[:, :, 2] = scratch
    return result


def main() -> dict[str, object]:
    rng = np.random.default_rng(20261111)
    rows = []
    for width, height in CASES:
        rgb = rng.random((height, width, 3), dtype=np.float32)
        for sx, sy in SHIFTS:
            dual = dual_workspace(rgb, sx, sy)
            reused = reused_workspace(rgb, sx, sy)
            rows.append({
                "width": width,
                "height": height,
                "shift R xy": [sx, sy],
                "shift B xy": [-sx, -sy],
                "exact RGB equality": bool(np.array_equal(dual, reused)),
                "max abs difference": float(np.max(np.abs(dual - reused))),
                "green preserved": bool(np.array_equal(rgb[:, :, 1], reused[:, :, 1])),
            })

    report = {
        "seed": 20261111,
        "protocol": "Compare source-order-equivalent CPU models: two independent float scratch planes versus one plane reused after R output is copied. Clamped integer coordinate sampling matches the Core lambda.",
        "limits": "Python model only; not C++ execution, allocator profiling, frame-time measurement, or GPU path validation.",
        "conditions": len(rows),
        "all exact": all(row["exact RGB equality"] for row in rows),
        "all green preserved": all(row["green preserved"] for row in rows),
        "scratch storage model": {
            "two buffers bytes per pixel": 8,
            "one reused buffer bytes per pixel": 4,
            "peak scratch reduction": 0.5,
            "note": "Source-level vector capacity only; excludes frame/channel storage, allocator metadata, parallel runtime, and timing. C++ vector value-initialization also writes zeros at construction.",
        },
        "cases": rows,
    }
    out_dir = ROOT / "captures" / "core-chromatic-workspace"
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "core-chromatic-workspace-metrics.json"
    path.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    fixture = {
        "origin": "Deterministic float32 random planes generated by this script; no external assets.",
        "seed": report["seed"],
        "dimensions": [f"{w}x{h}" for w, h in CASES],
        "shifts": [list(x) for x in SHIFTS],
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
    }
    (out_dir / "fixture-manifest.json").write_text(json.dumps(fixture, indent=2) + "\n", encoding="utf-8", newline="\n")
    return report


if __name__ == "__main__":
    result = main()
    print(f"Compared {result['conditions']} source-derived workspace cases; exact={result['all exact']}")
