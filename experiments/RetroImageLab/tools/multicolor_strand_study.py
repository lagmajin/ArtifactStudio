def opponent(rgb: np.ndarray) -> np.ndarray:
    linear = srgb_to_linear(rgb)
    return np.stack((linear[..., 0] - linear[..., 1],
                     linear[..., 2] - 0.5 * (linear[..., 0] + linear[..., 1])), axis=-1)


def measure_case(label: str, image: Image.Image, masks: dict[int, dict[str, np.ndarray]],
                 source_centers: dict[int, dict[str, np.ndarray]],
                 registration_axis: int = 1) -> dict[str, object]:
    rgb = np.asarray(image.convert("RGB"), dtype=np.float32) / 255.0
    chroma = opponent(rgb)
    result: dict[str, object] = {"treatment": label, "widths": {}}
    luminance = np.sum(rgb * np.asarray((0.2126, 0.7152, 0.0722), dtype=np.float32), axis=2)
    for strand_width, color_masks in masks.items():
        sample_policies: dict[str, dict[str, np.ndarray]] = {
            "strict source-line": {name: chroma[mask] for name, mask in color_masks.items()}
        }
        local_peak_values: dict[str, np.ndarray] = {}
        local_contrast_values: dict[str, np.ndarray] = {}
        for name, mask in color_masks.items():
            ys, xs = np.nonzero(mask)
            offsets = np.asarray((-2, -1, 0, 1, 2))
            if registration_axis == 1:
                cell_left = list(COLORS).index(name) * 128
                candidates = np.clip(xs[:, None] + offsets, cell_left, cell_left + 127)
                candidate_luma = luminance[ys[:, None], candidates]
                peak_x = candidates[np.arange(xs.size), np.argmax(candidate_luma, axis=1)]
                local_peak_values[name] = chroma[ys, peak_x]
                background_x = np.clip(xs + 4, cell_left, cell_left + 127)
                background_luma = luminance[ys, background_x]
                contrast_x = candidates[np.arange(xs.size), np.argmax(np.abs(candidate_luma - background_luma[:, None]), axis=1)]
                local_contrast_values[name] = chroma[ys, contrast_x]
            else:
                candidates = np.clip(ys[:, None] + offsets, 0, rgb.shape[0] - 1)
                candidate_luma = luminance[candidates, xs[:, None]]
                peak_y = candidates[np.arange(ys.size), np.argmax(candidate_luma, axis=1)]
                local_peak_values[name] = chroma[peak_y, xs]
                background_y = np.clip(ys + 4, 0, rgb.shape[0] - 1)
                background_luma = luminance[background_y, xs]
                contrast_y = candidates[np.arange(ys.size), np.argmax(np.abs(candidate_luma - background_luma[:, None]), axis=1)]
                local_contrast_values[name] = chroma[contrast_y, xs]
        axis_name = "x" if registration_axis == 1 else "y"
        sample_policies[f"local luminance peak within ±2px {axis_name}"] = local_peak_values
        sample_policies[f"local contrast peak within ±2px {axis_name}"] = local_contrast_values

        widths_result: dict[str, object] = {"line width px": strand_width, "sampling policies": {}}
        for policy_name, output_chroma in sample_policies.items():
            means: dict[str, np.ndarray] = {}
            within_rms: list[float] = []
            for name, values in output_chroma.items():
                means[name] = np.mean(values, axis=0)
                within_rms.append(float(np.sqrt(np.mean((values - means[name]) ** 2))))

            source_distances: list[float] = []
            output_distances: list[float] = []
            for left, right in combinations(COLORS, 2):
                source_distances.append(float(np.linalg.norm(source_centers[strand_width][left] - source_centers[strand_width][right])))
                output_distances.append(float(np.linalg.norm(means[left] - means[right])))

            confusion = {name: {candidate: 0 for candidate in COLORS} for name in COLORS}
            correct = total = 0
            references = np.stack([source_centers[strand_width][name] for name in COLORS])
            for name, values in output_chroma.items():
                predicted = np.argmin(np.sum((values[:, None, :] - references[None, :, :]) ** 2, axis=2), axis=1)
                for index, candidate in enumerate(COLORS):
                    confusion[name][candidate] = int(np.count_nonzero(predicted == index))
                own = list(COLORS).index(name)
                correct += int(np.count_nonzero(predicted == own))
                total += int(predicted.size)

            widths_result["sampling policies"][policy_name] = {
                "sampled pixels per color": int(next(iter(output_chroma.values())).shape[0]),
                "pairwise source opponent-chroma distance median": float(np.median(source_distances)),
                "pairwise output opponent-chroma distance median": float(np.median(output_distances)),
                "pairwise opponent-chroma distance retention": float(np.median(output_distances) / max(np.median(source_distances), 1e-12)),
                "minimum pairwise output opponent-chroma distance": float(np.min(output_distances)),
                "within-color opponent-chroma RMS": float(np.mean(within_rms)),
                "nearest-source-color accuracy": float(correct / max(total, 1)),
                "color confusion counts": confusion,
                "per-color output opponent-chroma centers": {name: means[name].tolist() for name in COLORS},
            }
        result["widths"][str(strand_width)] = widths_result
    return result


