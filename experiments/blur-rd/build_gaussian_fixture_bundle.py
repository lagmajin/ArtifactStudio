"""Build a deterministic float32 fixture bundle for Gaussian Blur R&D.

The bundle contains synthetic inputs only. It is not an Artifact capture and
does not claim to establish the production color/alpha contract.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np


ROOT = Path(__file__).resolve().parents[2]
OUTPUT_DIR = Path(__file__).resolve().parent / "fixtures" / "gaussian-r1"
SIZE = 513


def file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def make_fixtures() -> dict[str, np.ndarray]:
    height = width = SIZE
    y, x = np.mgrid[0:height, 0:width]
    center = SIZE // 2

    opaque = np.zeros((height, width, 4), dtype=np.float32)
    opaque[..., 3] = 1.0
    opaque[center, center, :3] = (0.07, 0.31, 1.5)  # physical BGRA
    opaque[center, center + 1, :3] = (0.4, 1.7, 0.03)
    opaque[center + 1, center, :3] = (2.0, -0.05, 0.6)

    alpha_edge = np.zeros_like(opaque)
    alpha_edge[..., 0] = 0.025
    alpha_edge[..., 1] = 0.18
    alpha_edge[..., 2] = 0.85
    alpha_edge[..., 3] = np.where(x < center, 0.0, 0.5).astype(np.float32)
    alpha_edge[..., :3] *= alpha_edge[..., 3:4]
    edge_patch = alpha_edge[center - 2:center + 3, center - 2:center + 3]
    edge_patch[..., :3] = (
        np.array((1.6, -0.08, 0.35), dtype=np.float32) * edge_patch[..., 3:4]
    )

    transparent_hidden = np.zeros_like(opaque)
    transparent_hidden[..., :3] = np.where(
        ((x // 16 + y // 16) % 2)[..., None] == 0,
        np.array((0.0, 0.0, 8.0), dtype=np.float32),
        np.array((7.0, -2.0, 0.0), dtype=np.float32),
    )
    transparent_hidden[..., 3] = 0.0

    hdr_edge = np.zeros_like(opaque)
    hdr_edge[..., 3] = 1.0
    hdr_edge[..., :3] = np.where(
        (x < center)[..., None],
        np.array((0.04, 0.3, 1.4), dtype=np.float32),
        np.array((1.8, -0.1, 0.06), dtype=np.float32),
    )

    subpixel = np.zeros_like(opaque)
    subpixel[..., 3] = 1.0
    subpixel[center, center - 1, :3] = (0.3, 0.15, 0.05)
    subpixel[center, center, :3] = (0.8, 0.5, 0.1)
    subpixel[center, center + 1, :3] = (0.15, 0.05, 0.9)

    transfer_edge = np.zeros_like(opaque)
    transfer_edge[..., 3] = 1.0
    transfer_edge[..., :3] = np.where(
        (x < center)[..., None],
        np.array((0.02, 0.1, 0.9), dtype=np.float32),
        np.array((0.85, 0.3, 0.05), dtype=np.float32),
    )

    return {
        "opaque_asymmetric_impulses": opaque,
        "premultiplied_alpha_edge_hdr": alpha_edge,
        "transparent_hidden_rgb_checker": transparent_hidden,
        "opaque_hdr_color_edge": hdr_edge,
        "opaque_three_pixel_detail": subpixel,
        "opaque_linear_srgb_transfer_edge": transfer_edge,
    }


def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    fixtures = make_fixtures()
    entries = []
    for name, array in fixtures.items():
        path = OUTPUT_DIR / f"{name}.npy"
        np.save(path, array, allow_pickle=False)
        entries.append({
            "name": name,
            "path": path.relative_to(ROOT).as_posix(),
            "sha256": file_sha256(path),
            "shape": list(array.shape),
            "dtype": str(array.dtype),
            "storage_order": "BGRA physical channel order",
            "logical_channel_mapping": {"R": 2, "G": 1, "B": 0, "A": 3},
            "alpha_association": (
                "premultiplied" if name == "premultiplied_alpha_edge_hdr"
                else "hidden_rgb_at_zero_alpha" if name == "transparent_hidden_rgb_checker"
                else "opaque"
            ),
            "transfer": "linear synthetic numeric values; not OCIO/display encoded",
            "seed": None,
            "source": "deterministic synthetic fixture generated by build_gaussian_fixture_bundle.py",
        })

    manifest = {
        "schema": "artifact.blur-rd.fixture-bundle.v1",
        "bundle": "Gaussian source evaluation fixtures r1",
        "created_date": "2026-11-12",
        "evidence_class": "synthetic evaluation input; not Artifact output or capture",
        "dimensions_px": [SIZE, SIZE],
        "dtype": "float32",
        "image_contract": {
            "memory_order": "BGRA",
            "logical_order": "RGBA",
            "primaries": "unspecified synthetic linear numeric space",
            "transfer": "linear numeric values",
            "alpha": "per fixture; see fixture-specific description",
            "clipping": "none; values outside [0,1] intentionally retained",
        },
        "fixtures": entries,
        "fixtures_source_sha256": file_sha256(Path(__file__).resolve()),
        "limitations": [
            "Synthetic inputs do not establish the application's active color configuration.",
            "Only Gaussian CPU/resident equation mirrors can consume these arrays today.",
            "Alpha interpretation for premultiplied_alpha_edge_hdr is authored by this generator, not inferred from Artifact runtime metadata.",
            "No visual acceptance, runtime routing, GPU dispatch, or performance claim is made.",
        ],
    }
    bundle_bytes = json.dumps(
        manifest, sort_keys=True, separators=(",", ":"), ensure_ascii=False
    ).encode("utf-8")
    manifest["bundle_identity_sha256"] = hashlib.sha256(bundle_bytes).hexdigest()
    manifest_path = OUTPUT_DIR / "manifest.json"
    manifest_path.write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    print(manifest_path)


if __name__ == "__main__":
    main()
